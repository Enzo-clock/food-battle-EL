BEGIN;

CREATE TABLE
    users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(50) NOT NULL UNIQUE,
        lastname VARCHAR(100) NOT NULL,
        firstname VARCHAR(100) NOT NULL,
        email VARCHAR(255) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        role VARCHAR(10) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin'))
    );

CREATE TABLE
    establishments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(150) NOT NULL,
        description TEXT,
        picture VARCHAR(255),
        city VARCHAR(80) NOT NULL,
        address TEXT NOT NULL,
        creator_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT
    );

CREATE TABLE
    categories (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL UNIQUE,
        slug VARCHAR(100) NOT NULL UNIQUE,
        color VARCHAR(20) NOT NULL DEFAULT 'lilac' CHECK (
            color IN ('peach', 'mint', 'lemon', 'lilac', 'pink', 'sky')
        ),
        -- image par défaut des plats de la catégorie qui n'ont pas leur propre photo
        picture VARCHAR(255) NOT NULL,
        creator_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE
    dishes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(150) NOT NULL,
        description TEXT,
        picture VARCHAR(255),
        price NUMERIC(6, 2) CHECK (price >= 0),
        creator_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
        establishment_id INTEGER REFERENCES establishments (id) ON DELETE RESTRICT
    );

CREATE TABLE
    dish_categories (
        dish_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE CASCADE,
        category_id INTEGER NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
        PRIMARY KEY (dish_id, category_id)
    );

CREATE TABLE
    tournaments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(150) NOT NULL,
        start_date DATE NOT NULL,
        creator_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT
    );

CREATE TABLE
    tournament_dishes (
        tournament_id INTEGER NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
        dish_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE RESTRICT,
        seed SMALLINT NOT NULL CHECK (seed BETWEEN 1 AND 8),
        PRIMARY KEY (tournament_id, dish_id),
        UNIQUE (tournament_id, seed)
    );

CREATE TABLE
    battles (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        creator_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
        tournament_id INTEGER REFERENCES tournaments (id) ON DELETE CASCADE,
        phase VARCHAR(10) CHECK (phase IN ('quarter', 'semi', 'final')),
        position SMALLINT CHECK (position BETWEEN 1 AND 7),
        battle_date DATE,
        dish_1_id INTEGER REFERENCES dishes (id) ON DELETE RESTRICT,
        dish_2_id INTEGER REFERENCES dishes (id) ON DELETE RESTRICT,
        dish_winner_id INTEGER REFERENCES dishes (id) ON DELETE RESTRICT,
        next_battle_id INTEGER REFERENCES battles (id) ON DELETE RESTRICT,
        next_slot SMALLINT CHECK (next_slot IN (1, 2)),
        UNIQUE (tournament_id, position),
        CONSTRAINT battles_free_battle_date_required CHECK (
            tournament_id IS NOT NULL
            OR battle_date IS NOT NULL
        ),
        CHECK (
            dish_1_id IS DISTINCT
            FROM
                dish_2_id
        ),
        CHECK (
            dish_winner_id IS NULL
            OR dish_winner_id IS NOT DISTINCT
            FROM
                dish_1_id
                OR dish_winner_id IS NOT DISTINCT
            FROM
                dish_2_id
        ),
        CHECK (
            (tournament_id IS NULL) = (phase IS NULL)
            AND (phase IS NULL) = (position IS NULL)
        ),
        CHECK ((next_battle_id IS NULL) = (next_slot IS NULL)),
        CHECK (
            next_battle_id IS DISTINCT
            FROM
                id
        )
    );

CREATE TABLE
    user_battle_votes (
        user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
        battle_id INTEGER NOT NULL REFERENCES battles (id) ON DELETE CASCADE,
        dish_choice_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE RESTRICT,
        vote_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (user_id, battle_id)
    );

CREATE TABLE
    tournament_runs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tournament_id INTEGER NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
        user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
        run_date DATE NOT NULL DEFAULT CURRENT_DATE,
        finished_at TIMESTAMP,
        UNIQUE (tournament_id, user_id, run_date)
    );

CREATE TABLE
    tournament_run_matches (
        run_id INTEGER NOT NULL REFERENCES tournament_runs (id) ON DELETE CASCADE,
        slot VARCHAR(2) NOT NULL CHECK (slot IN ('Q1', 'Q2', 'Q3', 'Q4', 'D1', 'D2', 'F')),
        dish_1_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE RESTRICT,
        dish_2_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE RESTRICT,
        dish_winner_id INTEGER REFERENCES dishes (id) ON DELETE RESTRICT,
        PRIMARY KEY (run_id, slot),
        CHECK (dish_1_id <> dish_2_id),
        CHECK (
            dish_winner_id IS NULL
            OR dish_winner_id IN (dish_1_id, dish_2_id)
        )
    );

