SET
    creator_id = u.id
FROM
    users u
WHERE
    u.username = 'enzOOO'
    AND d.id IN (
        SELECT
            dish_id
        FROM
            demo_dishes
    );

-- Crée les 12 battles libres : les plats 1-2, 3-4, 5-6 et 7-8 de chaque catégorie.
CREATE TEMP TABLE demo_battles ON COMMIT
DROP AS
WITH
    pairs AS (
        SELECT
            d1.category_slug,
            CAST((d1.seed + 1) / 2 AS SMALLINT) AS position,
            d1.dish_id AS dish_1_id,
            d2.dish_id AS dish_2_id
        FROM
            demo_dishes d1
            JOIN demo_dishes d2 ON d2.category_slug = d1.category_slug
            AND d2.seed = d1.seed + 1
        WHERE
            d1.seed IN (1, 3, 5, 7)
    ),
    inserted AS (
        INSERT INTO
            battles (
                creator_id,
                tournament_id,
                phase,
                position,
                battle_date,
                dish_1_id,
                dish_2_id
            )
        SELECT
            u.id,
            NULL,
            NULL,
            NULL,
            CURRENT_DATE,
            p.dish_1_id,
            p.dish_2_id
        FROM
            pairs p
            CROSS JOIN users u
        WHERE
            u.username = 'enzOOO' RETURNING id,
            dish_1_id,
            dish_2_id
    )
SELECT
    p.category_slug,
    p.position,
    i.id AS battle_id,
    p.dish_1_id,
    p.dish_2_id
FROM
    pairs p
    JOIN inserted i ON i.dish_1_id = p.dish_1_id
    AND i.dish_2_id = p.dish_2_id;

