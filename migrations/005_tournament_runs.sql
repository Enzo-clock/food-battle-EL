-- Migration 005 : parties de tournoi (fonctionnalité « Jouer un tournoi », PR #28).
--
-- Les deux tables ont été ajoutées à init.sql, qui ne s'exécute que sur une base VIDE.
-- Cette migration les crée sur une base existante, sans toucher aux données.
-- Idempotente (IF NOT EXISTS) : sans effet si les tables existent déjà.
--
--   Nouvelle base : exécutée automatiquement après les migrations précédentes (compose.yaml).
--   Base existante (PowerShell) :
--   Get-Content -Raw migrations/005_tournament_runs.sql | docker compose exec -T db psql -U foodbattle -d foodbattle

BEGIN;

-- Une partie : un joueur qui parcourt le tableau d'un tournoi, un jour donné.
CREATE TABLE IF NOT EXISTS tournament_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id INTEGER NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    run_date DATE NOT NULL DEFAULT CURRENT_DATE,
    finished_at TIMESTAMP,
    UNIQUE (tournament_id, user_id, run_date)
);

-- Les matchs de la partie : quarts (Q1–Q4), demies (D1, D2) et finale (F).
CREATE TABLE IF NOT EXISTS tournament_run_matches (
    run_id INTEGER NOT NULL REFERENCES tournament_runs (id) ON DELETE CASCADE,
    slot VARCHAR(2) NOT NULL CHECK (slot IN ('Q1', 'Q2', 'Q3', 'Q4', 'D1', 'D2', 'F')),
    dish_1_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE RESTRICT,
    dish_2_id INTEGER NOT NULL REFERENCES dishes (id) ON DELETE RESTRICT,
    dish_winner_id INTEGER REFERENCES dishes (id) ON DELETE RESTRICT,
    PRIMARY KEY (run_id, slot),
    CHECK (dish_1_id <> dish_2_id),
    CHECK (dish_winner_id IS NULL OR dish_winner_id IN (dish_1_id, dish_2_id))
);

COMMIT;
